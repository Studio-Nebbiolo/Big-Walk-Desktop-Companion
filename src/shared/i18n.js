  // 시스템 언어 목록(예: ['pt-BR', 'en-US'])에서 지원하는 첫 언어를 고른다.
  function match(locales) {
    for (const raw of locales || []) {
      const l = String(raw || '').toLowerCase().replace(/_/g, '-');
      if (!l) continue;
      if (l.startsWith('zh')) return /hant|-tw|-hk|-mo/.test(l) ? 'zh-TW' : 'zh-CN';
      const base = l.split('-')[0];
      if (STR[base]) return base;
    }
    return 'en';
  }

  // 설정값('auto' 또는 언어 코드)과 시스템 언어 목록으로 실제로 쓸 언어를 정한다.
  function resolve(pref, locales) {
    return STR[pref] ? pref : match(locales);
  }

  function translator(lang) {
    const table = STR[lang] || STR.en;
    const t = (key, params) => {
      let s = table[key] ?? STR.en[key] ?? key;
      if (params) s = s.replace(/\{(\w+)\}/g, (m, k) => (params[k] ?? m));
      return s;
    };
    t.lang = STR[lang] ? lang : 'en';
    t.color = (id) => {
      const i = COLOR_IDS.indexOf(id);
      return (table.colors || STR.en.colors)[i] ?? STR.en.colors[i] ?? id;
    };
    t.names = () => (table.names || STR.en.names).slice();
    return t;
  }

